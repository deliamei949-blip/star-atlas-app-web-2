import { useState, useEffect, useCallback, useRef } from 'react'
import { useStarStore } from '@/stores/starStore'
import { useSpeechRecognition } from '@/hooks/useSpeechRecognition'
import type { PulseLogSession } from '@/types'

interface PulseLogPanelProps {
  sourceCoord: string
  onClose: () => void
  onFlyToStar?: (starId: string) => void
  onViewDeductions?: (starId: string) => void
}

interface DistReport {
  matched: Array<{ starId: string; starName: string; paragraph: string }>
  unmatched: Array<{ paragraph: string }>
}

export default function PulseLogPanel({ sourceCoord, onClose, onFlyToStar, onViewDeductions }: PulseLogPanelProps) {
  const { stars, loadStars } = useStarStore()
  const [rawText, setRawText] = useState('')
  const [parsing, setParsing] = useState(false)
  const [report, setReport] = useState<DistReport | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [saved, setSaved] = useState(false)
  const textareaRef = useRef<HTMLTextAreaElement>(null)

  // ── 脉冲日志历史 ──
  const [showHistory, setShowHistory] = useState(false)
  const [sessions, setSessions] = useState<PulseLogSession[]>([])
  const [loadingHistory, setLoadingHistory] = useState(false)

  const loadHistory = useCallback(async () => {
    setLoadingHistory(true)
    try {
      const rows = await window.electronAPI.pulse.getBySource(sourceCoord)
      setSessions(rows || [])
    } catch {
      setSessions([])
    } finally {
      setLoadingHistory(false)
    }
  }, [sourceCoord])

  const handleOpenHistory = useCallback(() => {
    setShowHistory(true)
    loadHistory()
  }, [loadHistory])

  const handleRestoreSession = useCallback((rawText: string) => {
    setRawText(rawText)
    setShowHistory(false)
    setReport(null)
    setError(null)
  }, [])

  // ── 语音识别 ──
  const {
    isListening: isVoiceListening,
    isSupported: isVoiceSupported,
    interimText: voiceInterimText,
    toggle: toggleVoice,
  } = useSpeechRecognition({
    lang: 'zh-CN',
    continuous: true,
    onInterimResult: (text) => {
      // Real-time: write directly into the textarea as user speaks
      setRawText(text)
    },
    onFinalResult: (text) => {
      console.log('[PulseLogPanel] onFinalResult:', text.slice(0, 50))
      // Final result replaces interim — definitive transcription
      setRawText(text)
    },
    onError: (msg) => {
      console.error('[PulseLogPanel] Voice error:', msg)
      setError(msg)
    },
  })

  // Count stars for this source
  const sourceStars = stars.filter((s) => {
    // Stars are linked to captures with sourceApp matching sourceCoord
    return true // simplified — all stars shown for now
  })
  const pulsarCount = stars.filter((s) => s.form === 2).length

  useEffect(() => {
    loadStars()
  }, [loadStars])

  const handleParse = useCallback(async () => {
    if (!rawText.trim()) return
    setParsing(true)
    setError(null)
    try {
      const result = await window.electronAPI.pulse.parseAndDistribute({
        sessionId: '', // will be generated by IPC
        rawText: rawText.trim(),
        sourceCoord,
      })
      if (result.success) {
        setReport(result.data)
        // Reload stars so glow rings appear
        loadStars()
      } else {
        setError(result.error || '解析失败')
      }
    } catch (err: any) {
      setError(err?.message || '解析失败，请重试')
    } finally {
      setParsing(false)
    }
  }, [rawText, sourceCoord, loadStars])

  const handleSave = useCallback(async () => {
    if (!rawText.trim()) return
    try {
      await window.electronAPI.pulse.create({
        sourceCoord,
        rawText: rawText.trim(),
      })
      setSaved(true)
      setTimeout(() => setSaved(false), 2000)
    } catch (err: any) {
      setError(err?.message || '暂存失败')
    }
  }, [rawText, sourceCoord])

  const handleConfirmDistribute = useCallback(async () => {
    if (!report) return
    // Already distributed during parse — just close
    onClose()
  }, [report, onClose])

  return (
    <div className="fixed inset-0 z-[100] flex items-center justify-center bg-black/60">
      <div className="glass-panel w-[520px] max-h-[80vh] flex flex-col rounded-2xl overflow-hidden">
        {/* Header */}
        <div className="p-4 border-b border-white/5 flex items-center justify-between">
          <div>
            <h2 className="text-base font-medium text-star-glow">📡 脉冲日志</h2>
            <p className="text-xs text-ui-secondary mt-0.5">
              {sourceCoord} · 已点燃 {pulsarCount} 颗脉冲星
            </p>
          </div>
          <div className="flex items-center gap-2">
            {!report && (
              <button
                onClick={handleOpenHistory}
                className="text-xs text-ui-secondary/50 hover:text-ui-secondary transition-colors"
              >
                📋 历史
              </button>
            )}
            <button
              onClick={onClose}
              className="text-ui-secondary/50 hover:text-ui-secondary text-lg leading-none"
            >
              ✕
            </button>
          </div>
        </div>

        {/* Error */}
        {error && (
          <div className="px-4 pt-3">
            <p className="text-xs text-red-400 bg-red-400/10 px-2 py-1.5 rounded">{error}</p>
          </div>
        )}

        {/* Body */}
        <div className="flex-1 overflow-y-auto p-4">
          {/* ── History view ── */}
          {showHistory ? (
            <div className="space-y-3">
              <div className="flex items-center justify-between mb-2">
                <h3 className="text-sm text-ui-primary/80">📋 历史记录</h3>
                <button
                  onClick={() => setShowHistory(false)}
                  className="text-xs text-ui-secondary/50 hover:text-ui-secondary"
                >
                  返回
                </button>
              </div>
              {loadingHistory ? (
                <p className="text-xs text-ui-secondary/50 text-center py-8">⏳ 加载中…</p>
              ) : sessions.length === 0 ? (
                <p className="text-xs text-ui-secondary/50 text-center py-8">暂无历史记录</p>
              ) : (
                sessions.map((s) => (
                  <button
                    key={s.id}
                    onClick={() => handleRestoreSession(s.rawText)}
                    className="w-full text-left p-3 rounded-lg bg-white/[0.03] hover:bg-white/[0.06] border border-white/5 transition-colors"
                  >
                    <div className="flex items-center justify-between mb-1">
                      <span className="text-xs text-ui-secondary/50">
                        {new Date(s.createdAt).toLocaleDateString('zh-CN', {
                          month: 'short',
                          day: 'numeric',
                          hour: '2-digit',
                          minute: '2-digit',
                        })}
                      </span>
                      <span className="text-[10px] text-ui-secondary/30">
                        {s.rawText.length} 字
                      </span>
                    </div>
                    <p className="text-xs text-ui-primary/60 line-clamp-2">
                      {s.rawText.slice(0, 120)}
                    </p>
                  </button>
                ))
              )}
            </div>
          ) : !report ? (
            <>
              <p className="text-xs text-ui-secondary/60 mb-3">
                读完这篇文章后，把所有跨卡片的想法一次性写在这里。无需格式，想到什么写什么。
              </p>
              <div className="relative">
                <textarea
                  ref={textareaRef}
                  value={rawText}
                  onChange={(e) => setRawText(e.target.value)}
                  placeholder="我的散乱想法……&#10;&#10;比如：&#10;- 这个观点和之前那篇论文说的其实是同一件事……&#10;- 作者忽略了 XX 的可能性……&#10;- 这个框架可以用在 YY 场景……"
                  className="w-full bg-white/5 border border-white/10 rounded-xl px-4 py-3 pr-12 text-ui-primary text-sm resize-none outline-none placeholder:text-ui-secondary/30 focus:border-white/20 transition-colors"
                  rows={12}
                  disabled={parsing}
                />
                {/* 语音输入按钮 */}
                {isVoiceSupported && (
                  <button
                    onClick={toggleVoice}
                    disabled={parsing}
                    className={`absolute right-3 bottom-3 w-8 h-8 rounded-full flex items-center justify-center transition-all duration-200 disabled:opacity-30 disabled:cursor-not-allowed ${
                      isVoiceListening
                        ? 'bg-red-500/20 text-red-400 shadow-[0_0_12px_rgba(239,68,68,0.4)]'
                        : 'bg-white/5 text-ui-secondary/50 hover:text-ui-primary hover:bg-white/10'
                    }`}
                    title={isVoiceListening ? '停止录音' : '语音输入'}
                  >
                    {isVoiceListening ? (
                      <span className="relative">
                        {/* 脉冲动画圆环 */}
                        <span className="absolute inset-0 rounded-full bg-red-400/30 animate-ping" />
                        <svg width="16" height="16" viewBox="0 0 24 24" fill="currentColor">
                          <rect x="9" y="1" width="6" height="10" rx="3" />
                          <rect x="9" y="13" width="6" height="10" rx="3" />
                        </svg>
                      </span>
                    ) : (
                      <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
                        <path d="M12 1a3 3 0 0 0-3 3v8a3 3 0 0 0 6 0V4a3 3 0 0 0-3-3z" />
                        <path d="M19 10v2a7 7 0 0 1-14 0v-2" />
                        <line x1="12" y1="19" x2="12" y2="23" />
                        <line x1="8" y1="23" x2="16" y2="23" />
                      </svg>
                    )}
                  </button>
                )}
              </div>

              {/* 录音状态提示 */}
              {isVoiceListening && (
                <div className="flex items-center gap-2 mt-2 px-1">
                  <span className="relative flex h-2 w-2">
                    <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-red-400 opacity-75" />
                    <span className="relative inline-flex rounded-full h-2 w-2 bg-red-500" />
                  </span>
                  <span className="text-xs text-red-300/80">
                    正在聆听...
                  </span>
                  {voiceInterimText && (
                    <span className="text-xs text-ui-secondary/40 ml-2 italic truncate max-w-[300px]">
                      {voiceInterimText}
                    </span>
                  )}
                  <span className="text-xs text-ui-secondary/30 ml-auto">
                    点击 🎤 停止
                  </span>
                </div>
              )}
            </>
          ) : (
            /* Distribution Report */
            <div className="space-y-4">
              <div className="text-center">
                <p className="text-lg mb-1">✅ 解析完成</p>
              </div>

              {report.matched.length > 0 && (
                <div>
                  <h3 className="text-xs font-medium text-teal-300/80 mb-2">
                    已分发 ({report.matched.length})
                  </h3>
                  <div className="space-y-2">
                    {report.matched.map((m, i) => (
                      <div
                        key={i}
                        className="p-2.5 rounded-lg bg-white/[0.04] border border-white/5"
                      >
                        <p className="text-xs text-ui-primary/80 leading-relaxed mb-1.5">
                          &ldquo;{m.paragraph.slice(0, 100)}{m.paragraph.length > 100 ? '…' : ''}&rdquo;
                        </p>
                        <div className="flex items-center gap-3">
                          <button
                            onClick={() => onFlyToStar?.(m.starId)}
                            className="text-xs text-cyan-400/70 hover:text-cyan-300 transition-colors"
                          >
                            → [[💫 {m.starName || '脉冲星'}]]
                          </button>
                          <button
                            onClick={() => onViewDeductions?.(m.starId)}
                            className="text-xs text-teal-300/60 hover:text-teal-200 transition-colors"
                          >
                            💡 查看推演
                          </button>
                        </div>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {report.unmatched.length > 0 && (
                <div>
                  <h3 className="text-xs font-medium text-amber-300/60 mb-2">
                    游离想法 ({report.unmatched.length})
                  </h3>
                  <div className="space-y-2">
                    {report.unmatched.map((u, i) => (
                      <div
                        key={i}
                        className="p-2.5 rounded-lg bg-white/[0.03] border border-dashed border-white/5"
                      >
                        <p className="text-xs text-ui-primary/60 leading-relaxed">
                          &ldquo;{u.paragraph.slice(0, 120)}{u.paragraph.length > 120 ? '…' : ''}&rdquo;
                        </p>
                        <p className="text-xs text-ui-secondary/30 mt-1">已存入游离想法区</p>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {report.matched.length === 0 && report.unmatched.length === 0 && (
                <p className="text-center text-ui-secondary/50 text-sm py-4">
                  没有识别到可分发的内容，请尝试写更多想法
                </p>
              )}
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="p-4 border-t border-white/5 flex items-center justify-between">
          {!report ? (
            <>
              <div className="flex items-center gap-2">
                <button
                  onClick={handleSave}
                  disabled={!rawText.trim() || parsing}
                  className="px-4 py-1.5 text-xs text-ui-secondary hover:text-ui-primary rounded-md hover:bg-white/5 disabled:opacity-30 disabled:cursor-not-allowed transition-colors"
                >
                  {saved ? '✓ 已暂存' : '💾 暂存'}
                </button>
              </div>
              <div className="flex items-center gap-2">
                {parsing && (
                  <span className="text-xs text-ui-secondary/60">⏳ AI 解析中...</span>
                )}
                <button
                  onClick={handleParse}
                  disabled={!rawText.trim() || parsing}
                  className="px-4 py-1.5 text-xs bg-star-glow/20 text-star-glow rounded-md hover:bg-star-glow/30 disabled:opacity-30 disabled:cursor-not-allowed transition-all"
                >
                  🔮 解析并分发
                </button>
              </div>
            </>
          ) : (
            <div className="flex items-center justify-between w-full">
              <button
                onClick={() => {
                  setReport(null)
                  setRawText('')
                }}
                className="px-4 py-1.5 text-xs text-ui-secondary hover:text-ui-primary rounded-md hover:bg-white/5 transition-colors"
              >
                ✏️ 重新编辑
              </button>
              <button
                onClick={handleConfirmDistribute}
                className="px-4 py-1.5 text-xs bg-teal-500/20 text-teal-300 rounded-md hover:bg-teal-500/30 transition-all"
              >
                ✓ 确认分发
              </button>
            </div>
          )}
        </div>
      </div>
    </div>
  )
}
